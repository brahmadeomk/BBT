#!/usr/bin/env node
'use strict';

/**
 * Generate the "OSK Focus Watcher" global ui_template from src/hmi/osk-policy.js.
 *
 * A global dashboard template cannot `require()`, so the policy has to be
 * EMBEDDED in flows_BBT.json. That is a duplicate, and duplicates rot — so this
 * is the only thing allowed to write it, and `test/hmi/osk-policy.test.js`
 * fails if the flow's copy is not byte-identical to the module. Edit the module,
 * run this, re-import the flow.
 *
 * Usage: node tools/sync-osk-policy.js [--check]
 */

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const FLOWS = path.join(ROOT, 'flows', 'flows_BBT.json');
const POLICY = path.join(ROOT, 'src', 'hmi', 'osk-policy.js');

const WATCHER_ID = '05c0a11b0a5d0001';

/* The thin half: listeners in, fetch out. Everything that DECIDES is in the
 * policy above it. Deliberately vanilla DOM and not Angular — this template is
 * injected into the site head and has no scope of its own, and `focusin`
 * bubbles, so two listeners on the document cover every widget on every page
 * including ones drawn later by ng-repeat. */
const GLUE = `
<script>
(function () {
  "use strict";
  // Wrapped whole: an exception thrown from a focus listener must never be able
  // to take the alarm pages down with it.
  try {
    var P = window.BusductOskPolicy;
    if (!P) return;
    var policy = P.createOskPolicy();
    var timer = null;
    var inflight = false;
    var queued = null;

    // One request at a time, but the LATEST decision always gets through: a
    // hide arriving while a show is in flight must not be dropped, or the
    // keyboard stays up over the field the operator just left. Last write wins,
    // and a repeat of the command already sent is discarded.
    function send(command) {
      if (!command) return;
      if (inflight) { queued = command; return; }
      inflight = true;
      // Same origin as the dashboard, so no CORS and no credentials needed.
      fetch("/osk/" + command, { method: "POST", cache: "no-store" })
        .catch(function () { /* the keyboard is a convenience; never alert */ })
        .then(function () {
          inflight = false;
          var q = queued;
          queued = null;
          if (q && q !== command) send(q);
        });
    }

    function act(r) {
      send(r.command);
      if (timer) { clearTimeout(timer); timer = null; }
      if (r.nextTickMs != null) {
        var delay = Math.max(0, r.nextTickMs - Date.now());
        timer = setTimeout(function () { timer = null; act(policy.tick(Date.now())); }, delay);
      }
    }

    // A descriptor, not the node: the policy is pure and never touches the DOM.
    function describe(el) {
      if (!el) return null;
      return {
        tag: el.tagName,
        type: el.getAttribute ? el.getAttribute("type") : null,
        readOnly: !!el.readOnly,
        disabled: !!el.disabled,
        isContentEditable: !!el.isContentEditable,
      };
    }

    document.addEventListener("focusin", function (e) {
      act(policy.focus(describe(e.target), Date.now()));
    }, true);

    // focusout fires BEFORE the next focusin, so this only ever arms the hide;
    // the focusin that follows cancels it. That ordering is what stops the
    // keyboard flapping as the operator tabs across a table row.
    document.addEventListener("focusout", function () {
      act(policy.blur(Date.now()));
    }, true);

    document.addEventListener("keydown", function (e) {
      if (e.key === "Enter" && !e.shiftKey) act(policy.done());
    }, true);

    document.addEventListener("visibilitychange", function () {
      if (document.hidden) act(policy.pageHidden());
    });

    // On-demand, for a dashboard button: onBusductKeyboard() from any template.
    window.onBusductKeyboard = function () { act(policy.toggle()); };
  } catch (err) {
    if (window.console) console.warn("[busduct-osk]", err);
  }
})();
</script>
`;

function buildFormat() {
  const policy = fs.readFileSync(POLICY, 'utf8').trim();
  return [
    '<!-- GENERATED by tools/sync-osk-policy.js - do not hand-edit.',
    '     The decision logic below is src/hmi/osk-policy.js verbatim; a global',
    '     dashboard template cannot require(), so it is embedded and pinned by',
    '     test/hmi/osk-policy.test.js. Edit the module, re-run the tool. -->',
    '<script>',
    policy,
    '</script>',
    GLUE.trim(),
    '',
  ].join('\n');
}

function main() {
  const check = process.argv.includes('--check');
  const flows = JSON.parse(fs.readFileSync(FLOWS, 'utf8'));
  const node = flows.find((n) => n.id === WATCHER_ID);
  if (!node) {
    console.error(`node ${WATCHER_ID} ("OSK Focus Watcher") is not in the flow - add it first`);
    return 1;
  }
  const format = buildFormat();
  if (node.format === format) { console.log('flow is up to date'); return 0; }
  if (check) { console.error('OUT OF DATE - run: node tools/sync-osk-policy.js'); return 1; }
  node.format = format;
  fs.writeFileSync(FLOWS, JSON.stringify(flows));
  console.log(`updated "${node.name}" (${format.length} chars) - re-import the flow in Node-RED`);
  return 0;
}

if (require.main === module) process.exit(main());
module.exports = { buildFormat, WATCHER_ID };
